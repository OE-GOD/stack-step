/**
 * Running fuzz programs on a real x86-64 CPU.
 *
 * `nativeAssembly()` wraps every program in a function:
 *
 *     save the callee-saved registers
 *     remember rsp
 *     <the program>
 *     pushfq / pop → the flags;  mov → all 16 registers   (into `ss_result`)
 *     restore, ret
 *
 * `DRIVER_SOURCE` is a small C program that, for every function, clears the scratch
 * area, calls the function, and prints one JSON line with what was captured.
 * `parseDriverOutput()` reads those lines back and checks the harness itself: the stack
 * pointer is where it started, r15 still points at the scratch area, and the guard
 * bytes around the scratch area are untouched.
 */
import { SCRATCH_BYTES } from './model'
import { nativeBody, type FuzzProgram } from './program'

/** The 16 registers in x86 encoding order: the order of the `ss_result` slots. */
export const CAPTURE_ORDER = [
  'rax',
  'rcx',
  'rdx',
  'rbx',
  'rsp',
  'rbp',
  'rsi',
  'rdi',
  'r8',
  'r9',
  'r10',
  'r11',
  'r12',
  'r13',
  'r14',
  'r15',
] as const

export type CapturedRegister = (typeof CAPTURE_ORDER)[number]

const GUARD_BYTES = 64
const GUARD_VALUE = 0xa5

export interface NativeTarget {
  /** "_" on macOS (C names get a leading underscore), "" on Linux. */
  symbolPrefix: string
  /** True for ELF targets (Linux): adds the note that marks the stack non-executable. */
  elf: boolean
}

/** One assembly file with one function per program. */
export function nativeAssembly(programs: readonly FuzzProgram[], target: NativeTarget): string {
  const sym = (name: string): string => `${target.symbolPrefix}${name}`
  const out: string[] = []
  out.push('# Generated by scripts/make-cpu-fuzz-fixture.mjs. Do not edit.')
  out.push('    .intel_syntax noprefix')
  out.push('    .data')
  for (const name of [
    'ss_guard_low',
    'ss_scratch',
    'ss_guard_high',
    'ss_result',
    'ss_entry_rsp',
    'ss_programs',
    'ss_program_count',
  ]) {
    out.push(`    .globl ${sym(name)}`)
  }
  // The scratch area sits between two guard blocks. A program that writes outside the
  // scratch area damages a guard, and the driver reports it.
  out.push(`${sym('ss_guard_low')}:`)
  out.push(`    .fill ${GUARD_BYTES}, 1, ${GUARD_VALUE}`)
  out.push(`${sym('ss_scratch')}:`)
  out.push('scratch:')
  out.push(`    .zero ${SCRATCH_BYTES}`)
  out.push(`${sym('ss_guard_high')}:`)
  out.push(`    .fill ${GUARD_BYTES}, 1, ${GUARD_VALUE}`)
  out.push(`${sym('ss_result')}:`)
  out.push(`    .zero ${8 * (CAPTURE_ORDER.length + 1)}`)
  out.push(`${sym('ss_entry_rsp')}:`)
  out.push('    .quad 0')
  out.push(`${sym('ss_programs')}:`)
  for (const program of programs) out.push(`    .quad ${sym(`ss_run_${program.id}`)}`)
  out.push(`${sym('ss_program_count')}:`)
  out.push(`    .quad ${programs.length}`)
  out.push('')
  out.push('    .text')

  const result = sym('ss_result')
  const entryRsp = sym('ss_entry_rsp')
  for (const program of programs) {
    out.push('')
    out.push(`${sym(`ss_run_${program.id}`)}:`)
    for (const reg of ['rbp', 'rbx', 'r12', 'r13', 'r14', 'r15']) out.push(`    push ${reg}`)
    out.push(`    mov qword ptr ${entryRsp}[rip], rsp`)
    out.push(`# ---- ${program.id} ----`)
    out.push(nativeBody(program))
    out.push(`# ---- capture ----`)
    // Flags first: none of the lines below changes them, but this keeps the order obvious.
    out.push('    pushfq')
    out.push(`    pop qword ptr ${result}+${8 * CAPTURE_ORDER.length}[rip]`)
    CAPTURE_ORDER.forEach((reg, slot) => {
      const place = slot === 0 ? `${result}[rip]` : `${result}+${8 * slot}[rip]`
      out.push(`    mov qword ptr ${place}, ${reg}`)
    })
    // Go back to the remembered stack pointer even if a program were unbalanced.
    out.push(`    mov rsp, qword ptr ${entryRsp}[rip]`)
    for (const reg of ['r15', 'r14', 'r13', 'r12', 'rbx', 'rbp']) out.push(`    pop ${reg}`)
    out.push('    ret')
  }
  if (target.elf) {
    out.push('')
    out.push('    .section .note.GNU-stack,"",@progbits')
  }
  out.push('')
  return out.join('\n')
}

/** The C driver. It prints one JSON line per program. */
export const DRIVER_SOURCE = String.raw`/* Generated by scripts/make-cpu-fuzz-fixture.mjs. Do not edit. */
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define GUARD_BYTES ${GUARD_BYTES}
#define GUARD_VALUE ${GUARD_VALUE}
#define SCRATCH_BYTES ${SCRATCH_BYTES}
#define SLOTS ${CAPTURE_ORDER.length + 1}

extern uint8_t ss_guard_low[GUARD_BYTES];
extern uint8_t ss_scratch[SCRATCH_BYTES];
extern uint8_t ss_guard_high[GUARD_BYTES];
extern uint64_t ss_result[SLOTS];
extern uint64_t ss_entry_rsp;
extern void (*ss_programs[])(void);
extern uint64_t ss_program_count;

int main(void) {
  for (uint64_t i = 0; i < ss_program_count; i++) {
    memset(ss_guard_low, GUARD_VALUE, GUARD_BYTES);
    memset(ss_guard_high, GUARD_VALUE, GUARD_BYTES);
    memset(ss_scratch, 0, SCRATCH_BYTES);
    memset(ss_result, 0, sizeof ss_result);
    ss_entry_rsp = 0;

    ss_programs[i]();

    int guards = 1;
    for (int k = 0; k < GUARD_BYTES; k++) {
      if (ss_guard_low[k] != GUARD_VALUE || ss_guard_high[k] != GUARD_VALUE) guards = 0;
    }
    printf("{\"i\":%llu,\"r\":[", (unsigned long long)i);
    for (int k = 0; k < SLOTS - 1; k++) {
      printf("%s\"%llx\"", k == 0 ? "" : ",", (unsigned long long)ss_result[k]);
    }
    printf("],\"f\":\"%llx\",\"e\":\"%llx\",\"a\":\"%llx\",\"g\":%d,\"s\":\"",
           (unsigned long long)ss_result[SLOTS - 1], (unsigned long long)ss_entry_rsp,
           (unsigned long long)(uintptr_t)ss_scratch, guards);
    for (int k = 0; k < SCRATCH_BYTES; k++) printf("%02x", ss_scratch[k]);
    printf("\"}\n");
  }
  return 0;
}
`

export interface NativeResult {
  index: number
  registers: Record<CapturedRegister, bigint>
  flags: { CF: 0 | 1; ZF: 0 | 1; SF: 0 | 1; OF: 0 | 1 }
  /** The raw RFLAGS value, for the record. */
  rflags: bigint
  scratch: Uint8Array
}

function bit(value: bigint, position: bigint): 0 | 1 {
  return (value >> position) & 1n ? 1 : 0
}

/** RFLAGS → the four flags the emulator models: CF bit 0, ZF bit 6, SF bit 7, OF bit 11. */
export function flagsFromRflags(rflags: bigint): NativeResult['flags'] {
  return { CF: bit(rflags, 0n), ZF: bit(rflags, 6n), SF: bit(rflags, 7n), OF: bit(rflags, 11n) }
}

interface DriverLine {
  i: number
  r: string[]
  f: string
  e: string
  a: string
  g: number
  s: string
}

function isDriverLine(value: unknown): value is DriverLine {
  if (typeof value !== 'object' || value === null) return false
  const v = value as Record<string, unknown>
  return (
    typeof v.i === 'number' &&
    Array.isArray(v.r) &&
    v.r.length === CAPTURE_ORDER.length &&
    v.r.every((item) => typeof item === 'string') &&
    typeof v.f === 'string' &&
    typeof v.e === 'string' &&
    typeof v.a === 'string' &&
    typeof v.g === 'number' &&
    typeof v.s === 'string' &&
    v.s.length === 2 * SCRATCH_BYTES
  )
}

/**
 * Read the driver's output. Throws with a clear message when a line is damaged or when
 * the harness's own checks fail for a program.
 */
export function parseDriverOutput(
  stdout: string,
  programs: readonly FuzzProgram[],
): NativeResult[] {
  const lines = stdout.split('\n').filter((text) => text.trim() !== '')
  if (lines.length !== programs.length) {
    throw new Error(`The driver printed ${lines.length} lines for ${programs.length} programs.`)
  }
  return lines.map((text, position) => {
    const program = programs[position]
    if (program === undefined) throw new Error('More driver lines than programs.')
    let parsed: unknown
    try {
      parsed = JSON.parse(text)
    } catch {
      throw new Error(
        `Driver line ${position + 1} (${program.id}) is not JSON: ${text.slice(0, 80)}`,
      )
    }
    if (!isDriverLine(parsed)) {
      throw new Error(`Driver line ${position + 1} (${program.id}) has an unexpected shape.`)
    }
    if (parsed.i !== position) {
      throw new Error(
        `Driver line ${position + 1} is for program ${parsed.i}, expected ${position}.`,
      )
    }
    const registers = {} as Record<CapturedRegister, bigint>
    CAPTURE_ORDER.forEach((name, slot) => {
      registers[name] = BigInt(`0x${parsed.r[slot] ?? '0'}`)
    })
    const entryRsp = BigInt(`0x${parsed.e}`)
    const scratchAddress = BigInt(`0x${parsed.a}`)
    if (registers.rsp !== entryRsp) {
      throw new Error(
        `${program.id}: the stack is not balanced. rsp ended at 0x${registers.rsp.toString(16)}, ` +
          `it started at 0x${entryRsp.toString(16)}.`,
      )
    }
    if (registers.r15 !== scratchAddress) {
      throw new Error(`${program.id}: r15 no longer points at the scratch area.`)
    }
    if (parsed.g !== 1) {
      throw new Error(`${program.id}: the program wrote outside the scratch area.`)
    }
    const rflags = BigInt(`0x${parsed.f}`)
    const scratch = new Uint8Array(SCRATCH_BYTES)
    for (let k = 0; k < SCRATCH_BYTES; k++) {
      scratch[k] = Number.parseInt(parsed.s.slice(2 * k, 2 * k + 2), 16)
    }
    return { index: position, registers, flags: flagsFromRflags(rflags), rflags, scratch }
  })
}
