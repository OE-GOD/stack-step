/**
 * Driving gdb and lldb in batch mode, and reading what they print.
 *
 * Both debuggers get a generated command file: stop at the first instruction of `main`,
 * print the registers, then for every step of the plan run one instruction and print
 * the registers again. The parsers below are pure functions (text in, states out), so
 * they are tested with canned debugger output in `scripts/verify-native.test.ts`.
 */
import { REG64_NAMES, type Reg64 } from '../../../src/emulator/types'
import { flagsFromRflags, type NativeState, type NativeStep } from './state'

export interface DebuggerFiles {
  /** File the program reads as its standard input. */
  stdin: string
  /** File the program's output goes to (keeps it apart from the debugger's own text). */
  stdout: string
}

export interface DebuggerTrace {
  /** State 0 is the stop at `main`; state N is after N steps. */
  states: NativeState[]
  /** Why the trace is empty or shorter than planned, in one sentence; null when complete. */
  problem: string | null
}

const GDB_MARK = '@@STATE'

/** Quote a path for the shell that gdb uses to start the program. */
function shellQuote(text: string): string {
  return `'${text.replaceAll("'", `'\\''`)}'`
}

/* ─────────────────────────────────── gdb ─────────────────────────────────── */

/**
 * The gdb command file.
 *
 * `break *main` (with the star) stops at the very first instruction. Plain `break main`
 * would skip the `push rbp` / `mov rbp, rsp` at the start of the function.
 * An error in a command file ends the file, so a program that exits early simply gives
 * a shorter trace.
 */
export function gdbCommands(plan: readonly NativeStep[], files: DebuggerFiles): string {
  const registers = `info registers ${[...REG64_NAMES, 'rip', 'eflags'].join(' ')}`
  const lines = [
    '# Generated by scripts/verify-native.mjs',
    'set pagination off',
    'set confirm off',
    'set width 0',
    'set height 0',
    'break *main',
    `run < ${shellQuote(files.stdin)} > ${shellQuote(files.stdout)}`,
    `echo ${GDB_MARK} 0\\n`,
    registers,
  ]
  plan.forEach((step, position) => {
    lines.push(step === 'over' ? 'nexti' : 'stepi')
    lines.push(`echo ${GDB_MARK} ${position + 1}\\n`)
    lines.push(registers)
  })
  lines.push('')
  return lines.join('\n')
}

/** One line of `info registers`: name, value, and the "natural" column after it. */
export function parseGdbRegisterLine(
  line: string,
): { name: string; value: bigint; rest: string } | null {
  const match = /^([a-z][a-z0-9_]*)\s+0x([0-9a-fA-F]+)\s*(.*)$/.exec(line)
  if (!match) return null
  return { name: match[1] ?? '', value: BigInt(`0x${match[2] ?? '0'}`), rest: match[3] ?? '' }
}

/** `0x401126 <main+4>` → { symbol: 'main', offset: 4 }. */
function gdbLocation(rest: string): NativeState['location'] {
  const match = /<([^+>]+)(?:\+(\d+))?>/.exec(rest)
  if (!match) return null
  return { symbol: match[1] ?? '', offset: Number(match[2] ?? '0') }
}

function stateFrom(
  values: Map<string, bigint>,
  flagsName: string,
  location: NativeState['location'],
): NativeState | null {
  const registers = {} as Record<Reg64, bigint>
  for (const name of REG64_NAMES) {
    const value = values.get(name)
    if (value === undefined) return null
    registers[name] = value
  }
  const rip = values.get('rip')
  const flags = values.get(flagsName)
  if (rip === undefined || flags === undefined) return null
  return { registers, rip, flags: flagsFromRflags(flags), location }
}

function lastLines(output: string, count: number): string {
  const lines = output
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line !== '')
  return lines.slice(-count).join(' | ')
}

/** Read everything gdb printed for one command file made by `gdbCommands`. */
export function parseGdbTrace(output: string, plannedSteps: number): DebuggerTrace {
  const sections = new Map<
    number,
    { values: Map<string, bigint>; location: NativeState['location'] }
  >()
  let current: { values: Map<string, bigint>; location: NativeState['location'] } | null = null
  for (const line of output.split('\n')) {
    const mark = new RegExp(`^${GDB_MARK} (\\d+)\\s*$`).exec(line)
    if (mark) {
      current = { values: new Map(), location: null }
      sections.set(Number(mark[1]), current)
      continue
    }
    if (current === null) continue
    const register = parseGdbRegisterLine(line)
    if (register === null) continue
    current.values.set(register.name, register.value)
    if (register.name === 'rip') current.location = gdbLocation(register.rest)
  }

  const states: NativeState[] = []
  for (let index = 0; ; index++) {
    const section = sections.get(index)
    if (section === undefined) break
    const state = stateFrom(section.values, 'eflags', section.location)
    if (state === null) break
    states.push(state)
  }

  if (states.length === 0) {
    return {
      states,
      problem: `gdb did not stop at main (its last words: ${lastLines(output, 3) || 'nothing'})`,
    }
  }
  const start = states[0]?.location
  if (start !== null && start !== undefined && (start.symbol !== 'main' || start.offset !== 0)) {
    return {
      states: [],
      problem: `gdb stopped at ${start.symbol}+${start.offset}, not at the first instruction of main`,
    }
  }
  if (states.length < plannedSteps + 1) {
    return {
      states,
      problem: `gdb gave ${states.length - 1} of ${plannedSteps} steps (its last words: ${lastLines(output, 2)})`,
    }
  }
  return { states, problem: null }
}

/* ─────────────────────────────────── lldb ────────────────────────────────── */

const LLDB_REGISTERS = [...REG64_NAMES, 'rip', 'rflags']

/**
 * The lldb command file. `--skip-prologue false` makes the breakpoint stop at the very
 * first instruction of `main` (lldb otherwise skips `push rbp` / `mov rbp, rsp`).
 */
export function lldbCommands(plan: readonly NativeStep[], files: DebuggerFiles): string {
  const registers = `register read ${LLDB_REGISTERS.join(' ')}`
  const lines = [
    'settings set auto-confirm true',
    'settings set stop-disassembly-display never',
    'breakpoint set --name main --skip-prologue false',
    `process launch --stdin ${JSON.stringify(files.stdin)} --stdout ${JSON.stringify(files.stdout)}`,
    registers,
  ]
  for (const step of plan) {
    lines.push(step === 'over' ? 'thread step-inst-over' : 'thread step-inst')
    lines.push(registers)
  }
  lines.push('process kill', '')
  return lines.join('\n')
}

/** One line of `register read`: `     rip = 0x0000000100003f60  prog`main + 4`. */
export function parseLldbRegisterLine(
  line: string,
): { name: string; value: bigint; rest: string } | null {
  const match = /^\s*([a-z][a-z0-9]*) = 0x([0-9a-fA-F]+)\s*(.*)$/.exec(line)
  if (!match) return null
  return { name: match[1] ?? '', value: BigInt(`0x${match[2] ?? '0'}`), rest: match[3] ?? '' }
}

/** `` prog`main + 4 `` → { symbol: 'main', offset: 4 }. */
function lldbLocation(rest: string): NativeState['location'] {
  const match = /`(\S+?)(?: \+ (\d+))?\s*$/.exec(rest)
  if (!match) return null
  return { symbol: match[1] ?? '', offset: Number(match[2] ?? '0') }
}

/**
 * Read everything lldb printed for one command file made by `lldbCommands`.
 * Every `register read` prints its registers in the order asked, starting with rax, so
 * a new state starts at every `rax` line.
 */
export function parseLldbTrace(output: string, plannedSteps: number): DebuggerTrace {
  const blocks: { values: Map<string, bigint>; location: NativeState['location'] }[] = []
  for (const line of output.split('\n')) {
    const register = parseLldbRegisterLine(line)
    if (register === null || !LLDB_REGISTERS.includes(register.name)) continue
    if (register.name === 'rax') blocks.push({ values: new Map(), location: null })
    const block = blocks.at(-1)
    if (block === undefined) continue
    block.values.set(register.name, register.value)
    if (register.name === 'rip') block.location = lldbLocation(register.rest)
  }

  const states: NativeState[] = []
  for (const block of blocks) {
    const state = stateFrom(block.values, 'rflags', block.location)
    if (state === null) break
    states.push(state)
  }

  if (states.length === 0) {
    return {
      states,
      problem: `lldb did not stop at main (its last words: ${lastLines(output, 3) || 'nothing'})`,
    }
  }
  const start = states[0]?.location
  if (start !== null && start !== undefined && (start.symbol !== 'main' || start.offset !== 0)) {
    return {
      states: [],
      problem: `lldb stopped at ${start.symbol} + ${start.offset}, not at the first instruction of main`,
    }
  }
  if (states.length < plannedSteps + 1) {
    return {
      states,
      problem: `lldb gave ${states.length - 1} of ${plannedSteps} steps (its last words: ${lastLines(output, 2)})`,
    }
  }
  return { states, problem: null }
}

/* ──────────────────────────────── symbols ────────────────────────────────── */

/**
 * The output of `nm`: the address of every label in the built program.
 * Lines look like "0000000000401126 T main" (Linux) or "00000001000003ee T _main"
 * (macOS). Undefined names (U) and constants (a, A: `.equ` values) are left out.
 */
export function parseNm(output: string): Map<string, bigint> {
  const symbols = new Map<string, bigint>()
  for (const line of output.split('\n')) {
    const match = /^([0-9a-fA-F]+)\s+([A-Za-z])\s+(\S+)$/.exec(line.trim())
    if (!match) continue
    const kind = match[2] ?? ''
    if (kind === 'a' || kind === 'A' || kind === 'U') continue
    symbols.set(match[3] ?? '', BigInt(`0x${match[1] ?? '0'}`))
  }
  return symbols
}
