/**
 * The built-in single-step tracer (macOS, x86-64).
 *
 * A debugger is not always usable: on a Mac, lldb needs a permission that asks for a
 * password. This tracer needs nothing. The program is linked with the small C driver
 * below. The driver switches on the x86 trap flag and calls the program's `main`. With
 * the trap flag set, the CPU raises SIGTRAP after EVERY instruction, and the signal
 * handler gets a full copy of the registers. That is the same information a debugger's
 * `stepi` gives.
 *
 * The handler keeps a state whenever the instruction that just ran, or the one that
 * runs next, is inside the program's own code. Library code (printf, scanf) is stepped
 * through but not kept. When `main` returns (or the program calls `exit`), the driver
 * writes the kept states to the file named on its command line.
 *
 * The handler runs on its own stack, so nothing is written below the program's rsp.
 */
import { REG64_NAMES, type Reg64 } from '../../../src/emulator/types'
import { flagsFromRflags, type NativeState } from './state'

/** Names the program must use so that the driver can find it. */
export const TRACER_ENTRY = 'ss_program_main'
export const TRACER_TEXT_START = 'ss_text_start'
export const TRACER_TEXT_END = 'ss_text_end'

/** At most this many states are kept (the emulator's own limit is 10 000 steps). */
const MAX_ENTRIES = 40_000

