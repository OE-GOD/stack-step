export interface TracerEntry {
  /** Address of the instruction that just ran (0 for the very first state). */
  from: bigint
  state: NativeState
}

export interface TracerOutput {
  /** Run-time address of the program's `main`. */
  main: bigint
  textStart: bigint
  textEnd: bigint
  /** How many single steps the CPU took in all (library code included). */
  traps: number
  /** True when `main` returned; false when the program ended inside `exit`. */
  returned: boolean
  overflowed: boolean
  entries: TracerEntry[]
}

/** The order of the 16 register columns in a `step` line (x86 encoding order). */
const COLUMN_ORDER: readonly Reg64[] = REG64_NAMES

/** Read the tracer's file. Returns null when the file is not complete. */
export function parseTracerOutput(text: string): TracerOutput | null {
  const lines = text.split('\n').filter((line) => line !== '')
  if (lines.at(-1) !== 'end') return null
  const header = new Map<string, string[]>()
  const entries: TracerEntry[] = []
  for (const line of lines) {
    const [word, ...fields] = line.split(' ')
    if (word === undefined || word === 'end') continue
    if (word !== 'step') {
      header.set(word, fields)
      continue
    }
    if (fields.length !== 3 + COLUMN_ORDER.length) return null
    const numbers = fields.map((field) => BigInt(`0x${field}`))
    const [from, rip, rflags] = numbers
    if (from === undefined || rip === undefined || rflags === undefined) return null
    const registers = {} as Record<Reg64, bigint>
    COLUMN_ORDER.forEach((name, column) => {
      registers[name] = numbers[3 + column] ?? 0n
    })
    entries.push({
      from,
      state: { registers, rip, flags: flagsFromRflags(rflags), location: null },
    })
  }
  const number = (name: string, position = 0): bigint | null => {
    const field = header.get(name)?.[position]
    return field === undefined ? null : BigInt(`0x${field}`)
  }
  const main = number('main')
  const textStart = number('text', 0)
  const textEnd = number('text', 1)
  if (main === null || textStart === null || textEnd === null) return null
  return {
    main,
    textStart,
    textEnd,
    traps: Number(header.get('traps')?.[0] ?? '0'),
    returned: header.get('returned')?.[0] === '1',
    overflowed: header.get('overflowed')?.[0] === '1',
    entries,
  }
}

/**
 * The states that line up with the emulator's steps:
 *   - the state when `main` starts;
 *   - the state after every instruction of the program;
 *   - for a library call: only the state after the call came back;
 *   - the state after `main`'s final `ret` (which is outside the program again).
 */
export function tracerStates(output: TracerOutput): NativeState[] {
  const inside = (address: bigint): boolean =>
    address >= output.textStart && address < output.textEnd
  const states: NativeState[] = []
  output.entries.forEach((entry, position) => {
    const last = position === output.entries.length - 1
    if (inside(entry.state.rip) || (last && output.returned)) states.push(entry.state)
  })
  return states
}
